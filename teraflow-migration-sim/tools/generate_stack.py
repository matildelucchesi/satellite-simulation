"""Generate one Compose group from the pinned host and laboratory templates."""
import copy
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]


def build(root=ROOT):
    deploy = root / 'deploy'
    host = yaml.safe_load((deploy / 'compose.yaml').read_text())
    patches = yaml.safe_load((deploy / 'l2-patched.yaml').read_text())['services']
    laboratory = yaml.safe_load((deploy / 'lab.yaml').read_text())
    stack = {'name': 'teraflow', 'services': {}, 'networks': {
        'sat-a': {'ipam': {'config': [{'subnet': '${SAT_A_SUBNET:-172.26.0.0/16}'}]}},
        'sat-b': {'ipam': {'config': [{'subnet': '${SAT_B_SUBNET:-172.27.0.0/16}'}]}},
        'lab': {'name': 'tfs-migration-lab',
            'ipam': {'config': [{'subnet': '${LAB_SUBNET:-172.25.0.0/16}'}]}}}, 'volumes': {}}
    for role, port in (('sat-a', 18080), ('sat-b', 18081)):
        for name, original in host['services'].items():
            service = copy.deepcopy(original)
            service.update(copy.deepcopy(patches.get(name, {})))
            service['container_name'] = role + '-' + name + '-1'
            service['labels'] = {'org.teraflow.role': role}
            service['networks'] = {role: {'aliases': [name]}}
            if 'depends_on' in service:
                service['depends_on'] = {role + '-' + key: value
                                         for key, value in service['depends_on'].items()}
            if 'volumes' in service:
                service['volumes'] = [role + '-' + mount if mount.split(':')[0] in host['volumes']
                                      else mount for mount in service['volumes']]
            if name == 'deviceservice':
                service['volumes'] = ['..:/experiment:ro']
                service['networks']['lab'] = {}
                service['depends_on']['p4-proxy'] = {'condition': 'service_healthy'}
            if name == 'nbiservice':
                service['ports'] = [f'127.0.0.1:{port}:8080']
            stack['services'][role + '-' + name] = service
        for name in host['volumes']:
            stack['volumes'][role + '-' + name] = {'external': True, 'name': role + '_' + name}
    for name, original in laboratory['services'].items():
        service = copy.deepcopy(original)
        service['networks'] = {'lab': {'ipv4_address':
            '${P4_PROXY_IP:-172.25.0.3}' if name == 'p4-proxy' else '${MININET_IP:-172.25.0.2}'}}
        if name == 'p4-proxy':
            service['depends_on'] = {'mininet': {'condition': 'service_healthy'}}
            service['healthcheck'] = {'test': ['CMD', 'python', '-c',
                "import urllib.request; urllib.request.urlopen('http://localhost:8090/',timeout=3)"],
                'interval': '5s', 'timeout': '5s', 'retries': 30, 'start_period': '15s'}
        else:
            service['healthcheck'] = {'test': ['CMD', 'python3', '-c',
                "import json,urllib.request; s=json.load(urllib.request.urlopen('http://localhost:8089/',timeout=3)); f=json.load(open('/experiment/config/fixture.json')); assert s['switch_count']==len(f['emulator']['devices']) and s['switches_alive']"],
                'interval': '5s', 'timeout': '5s', 'retries': 30, 'start_period': '15s'}
        stack['services'][name] = service
    stack['volumes']['proxy-state'] = {'external': True, 'name': 'migration-lab_proxy-state'}
    return stack


if __name__ == '__main__':
    destination = ROOT / 'deploy/stack.yaml'
    destination.write_text('# Generated by tools/generate_stack.py; edit the source templates.\n' +
                           yaml.safe_dump(build(), sort_keys=False), encoding='utf-8')
    print(destination)
